using CRMS.Application.CreditCheck;
using CRMS.Application.CustomerCheck;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace CRMS.Infrastructure.Documents;

/// <summary>
/// The branded report of one staff credit check, individual or company: who ran it and why, the
/// advisory headline, then every section the check ran, as it was found. Masking is the check's
/// own: account numbers show their last four digits, phone numbers are partly hidden.
/// </summary>
public class CreditCheckPdfGenerator : ICreditCheckPdfGenerator
{
    private const string Primary = BoaBrand.Primary;
    private const string Accent = BoaBrand.Accent;
    private const string Subtle = BoaBrand.Subtle;
    private const string PanelGreen = BoaBrand.PanelGreen;
    private const string LightGray = BoaBrand.LightGray;
    private const string MedGray = BoaBrand.MediumGray;
    private const string Red = "#9b2c2c";
    private const string Amber = "#975a16";

    private static readonly TimeSpan Wat = TimeSpan.FromHours(1);

    public byte[] Generate(StaffCreditCheckView view, DateTime printedAt, string printedBy)
    {
        QuestPDF.Settings.License = LicenseType.Community;
        var isCompany = view.Company is not null;

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.MarginHorizontal(38);
                page.MarginVertical(30);
                page.DefaultTextStyle(x => x.FontSize(9).FontFamily("Arial"));

                page.Header().Element(c => Header(c, view, isCompany));
                page.Content().PaddingTop(10).Column(col =>
                {
                    RequestPanel(col, view);
                    if (view.Individual is { } i) Individual(col, i);
                    if (view.Company is { } co) Company(col, co);
                });
                page.Footer().Element(c => Footer(c, printedAt, printedBy));
            });
        }).GeneratePdf();
    }

    // ── Frame ────────────────────────────────────────────────────────────────────────────────────

    private static void Header(IContainer container, StaffCreditCheckView view, bool isCompany)
    {
        container.Column(col =>
        {
            col.Item().Height(5).Background(Color.FromHex(Primary));
            col.Item().PaddingTop(8).Row(row =>
            {
                row.ConstantItem(60).AlignMiddle().Element(c => BoaBrand.RenderLogo(c, 50));
                row.RelativeItem().AlignMiddle().Column(t =>
                {
                    t.Item().Text("BANK OF AGRICULTURE").Bold().FontSize(13).FontColor(Color.FromHex(Primary));
                    t.Item().Text(isCompany ? "Company Credit Check" : "Individual Credit Check").FontSize(11).FontColor(Color.FromHex(Accent));
                    t.Item().Text("Confidential: for the bank's credit assessment only").FontSize(7.5f).Italic().FontColor(Colors.Grey.Darken1);
                });
                row.ConstantItem(170).AlignMiddle().Column(m =>
                {
                    m.Item().AlignRight().Text(view.Summary.SubjectLabel).Bold().FontSize(8.5f).FontColor(Color.FromHex(Primary));
                    m.Item().AlignRight().Text($"Run {Local(view.Summary.CreatedAt):dd MMM yyyy HH:mm} WAT").FontSize(8).FontColor(Colors.Grey.Darken2);
                });
            });
            col.Item().PaddingTop(6).LineHorizontal(2).LineColor(Color.FromHex(Primary));
        });
    }

    private static void Footer(IContainer container, DateTime printedAt, string printedBy)
    {
        container.Column(col =>
        {
            col.Item().LineHorizontal(0.5f).LineColor(Color.FromHex(MedGray));
            col.Item().PaddingTop(3).Row(row =>
            {
                row.RelativeItem().Text($"Printed {Local(printedAt):dd MMM yyyy HH:mm} WAT by {printedBy}. Generated by the CRMS from the providers' answers at the time of the check.")
                    .FontSize(7).FontColor(Colors.Grey.Darken1);
                row.ConstantItem(60).AlignRight().Text(t =>
                {
                    t.DefaultTextStyle(x => x.FontSize(7).FontColor(Colors.Grey.Darken1));
                    t.Span("Page ");
                    t.CurrentPageNumber();
                    t.Span(" of ");
                    t.TotalPages();
                });
            });
        });
    }

    private static void RequestPanel(ColumnDescriptor col, StaffCreditCheckView view)
    {
        var s = view.Summary;
        col.Item().PaddingBottom(10).Background(Color.FromHex(PanelGreen)).Padding(8).Table(t =>
        {
            t.ColumnsDefinition(c => { c.RelativeColumn(1); c.RelativeColumn(2); c.RelativeColumn(1); c.RelativeColumn(2); });
            Pair(t, "Subject", s.SubjectName ?? s.SubjectLabel);
            Pair(t, "Run by", s.RequestedByName);
            Pair(t, "Identifier", s.SubjectLabel);
            Pair(t, "Case reference", s.CaseReference ?? "None given");
            Pair(t, "Reason", s.Purpose);
            Pair(t, "Took", view.DurationMs > 0 ? $"{view.DurationMs / 1000.0:N0} seconds" : "-");
        });

        static void Pair(TableDescriptor t, string label, string value)
        {
            t.Cell().PaddingVertical(2).Text(label).FontSize(8).FontColor(Colors.Grey.Darken2);
            t.Cell().PaddingVertical(2).Text(value).FontSize(8.5f).SemiBold();
        }
    }

    // ── Individual ───────────────────────────────────────────────────────────────────────────────

    private static void Individual(ColumnDescriptor col, CustomerCheckResponse r)
    {
        Headline(col, r.AiAdvisory, r.Warnings);

        Section(col, "Identity (BVN)", r.Identity.Status, r.Identity.Reason, c =>
        {
            var i = r.Identity;
            Facts(c, ("Name", i.FullName), ("Date of birth", D(i.DateOfBirth)), ("Gender", i.Gender), ("Phone", i.PhoneNumber),
                ("State of residence", i.StateOfResidence), ("Enrolment bank", i.EnrollmentBank),
                ("Registered", D(i.RegistrationDate)), ("Watch-listed", i.WatchListed is null ? null : i.WatchListed.Value ? "YES" : "No"),
                ("Source", i.Source));
        });
        Bureau(col, r.CreditBureau);
        Fraud(col, r.FraudCheck);
        Accounts(col, r.BankAccounts);
        Loans(col, r.BankLoans);
        Crms(col, r.CrmsFacilities);
        Advisory(col, r.AiAdvisory);
    }

    // ── Company ──────────────────────────────────────────────────────────────────────────────────

    private static void Company(ColumnDescriptor col, CompanyCheckResponse r)
    {
        Headline(col, r.AiAdvisory, r.Warnings);

        Section(col, "Company registration (CAC)", r.CompanyRegistration.Status, r.CompanyRegistration.Reason, c =>
        {
            var g = r.CompanyRegistration;
            Facts(c, ("Registered name", g.CompanyName), ("Number", g.RcNumber is null ? null : $"{g.CompanyType} {g.RcNumber}".Trim()),
                ("Status", g.RegistrationStatus), ("Registered", D(g.RegistrationDate)), ("Address", g.Address), ("State", g.State),
                ("Email", g.Email), ("Nature of business", g.NatureOfBusiness), ("Share capital", N(g.ShareCapital)));
            if (g.Affiliates.Count > 0)
            {
                c.Item().PaddingTop(6).Text($"Directors, shareholders and officers ({g.Affiliates.Count})").SemiBold().FontSize(8.5f);
                Grid(c, ["Name", "Role", "Status", "Appointed", "Shares"],
                    g.Affiliates.Select(a => new[]
                    {
                        a.Name + (a.IsChairman ? " (Chairman)" : "") + (a.IsCorporate ? " (company)" : ""),
                        a.Role ?? "-", a.Status ?? "-", D(a.AppointedOn) ?? "-",
                        a.Shares is { } sh ? $"{sh:N0}{(a.TypeOfShares is null ? "" : " " + a.TypeOfShares)}" : "-",
                    }), [3, 1.6f, 1.2f, 1.2f, 1.6f]);
            }
        });
        Bureau(col, r.CreditBureau);
        Fraud(col, r.FraudCheck);
        Accounts(col, r.BankAccounts);
        Loans(col, r.BankLoans);
        Crms(col, r.CrmsFacilities);
        Advisory(col, r.AiAdvisory);
    }

    // ── Shared sections ──────────────────────────────────────────────────────────────────────────

    private static void Headline(ColumnDescriptor col, AiAdvisorySection a, IReadOnlyList<string> warnings)
    {
        col.Item().PaddingBottom(10).Border(1).BorderColor(Color.FromHex(MedGray)).Padding(8).Row(row =>
        {
            row.ConstantItem(110).AlignMiddle().Column(c =>
            {
                c.Item().Text("ADVISORY SCORE").FontSize(7).FontColor(Colors.Grey.Darken1);
                c.Item().Text(a.Status == SectionStatuses.Ok ? $"{a.OverallScore:N1} / 100" : "Not available")
                    .Bold().FontSize(15).FontColor(Color.FromHex(ScoreColour(a.OverallScore)));
                if (a.Status == SectionStatuses.Ok)
                    c.Item().Text($"{Spaced(a.OverallRating)} risk · {Spaced(a.Recommendation)}").FontSize(8).SemiBold();
            });
            row.RelativeItem().PaddingLeft(10).Column(c =>
            {
                c.Item().Text(warnings.Count == 0 ? "Nothing flagged for a second look." : "Worth a second look").SemiBold().FontSize(8.5f)
                    .FontColor(Color.FromHex(warnings.Count == 0 ? Accent : Amber));
                foreach (var w in warnings)
                    c.Item().PaddingTop(1).Text($"• {w}").FontSize(8);
            });
        });
    }

    private static void Bureau(ColumnDescriptor col, CreditBureauSection b)
    {
        Section(col, "Credit bureau", b.Status, b.Reason, c =>
        {
            var s = b.Summary;
            Facts(c, ("Bureau", b.Bureau switch { "FIRST_CENTRAL" => "First Central", "CREDIT_REGISTRY" => "Credit Registry", var x => x }), ("Report date", b.ReportDate is { } d ? $"{Local(d):dd MMM yyyy}" : null),
                ("Credit score", b.Score is { } sc ? $"{sc.Value}{(sc.Band is null ? "" : $" ({sc.Band})")}" : null),
                ("Loans", s is null ? null : $"{s.TotalLoans} ({s.ActiveLoans} active, {s.ClosedLoans} closed)"),
                ("Performing / delinquent", s is null ? null : $"{s.PerformingLoans} / {s.DelinquentLoans}"),
                ("Outstanding", s is null ? null : N(s.TotalOutstanding)), ("Overdue", s is null ? null : N(s.TotalOverdue)),
                ("Worst arrears", s is null ? null : $"{s.MaxDaysOverdue} days"),
                ("Skipped", b.BureausSkipped.Count == 0 ? null : string.Join(", ", b.BureausSkipped)));
            if (b.Loans.Count > 0)
                Grid(c, ["Lender", "Type", "Amount", "Outstanding", "Overdue", "Status"],
                    b.Loans.Select(l => new[] { l.Lender ?? "-", l.Type ?? "-", N(l.Amount)!, N(l.Outstanding)!, N(l.Overdue)!, Spaced(l.Status) }),
                    [2.4f, 1.6f, 1.2f, 1.2f, 1.1f, 1.1f]);
            if (b.RecentEnquiries.Count > 0)
                c.Item().PaddingTop(4).Text("Recent enquiries: " + string.Join("; ", b.RecentEnquiries.Select(e => $"{e.Institution} ({D(e.Date)})"))).FontSize(7.5f);
        });
    }

    private static void Fraud(ColumnDescriptor col, FraudCheckSection f)
    {
        Section(col, "Fraud check", f.Status, f.Reason, c =>
        {
            Facts(c, ("Risk score", f.RiskScore?.ToString()), ("Risk band", f.RiskBand), ("Recommendation", f.Recommendation),
                ("AML screen", f.AmlChecked ? "Included" : "Not included"),
                ("Financial analysis", f.FinancialAnalysis is null ? null : f.FinancialAnalysis.Assessed ? "Assessed" : "Not assessed"));
            if (f.FinancialAnalysis?.Reason is { } why)
                c.Item().PaddingTop(2).Text(why).FontSize(7.5f).Italic().FontColor(Colors.Grey.Darken1);
        });
    }

    private static void Accounts(ColumnDescriptor col, BankAccountsSection a)
    {
        Section(col, "Accounts with the bank", a.Status, a.Reason, c =>
        {
            Facts(c, ("Customer record", a.ClientId), ("Record status", a.ClientStatus), ("KYC level", a.KycLevel), ("Customer since", D(a.CustomerSince)));
            if (a.Accounts.Count > 0)
                Grid(c, ["Account", "Product", "Status", "Balance", "Credits in window", "Last transaction"],
                    a.Accounts.Select(x => new[]
                    {
                        $"****{x.AccountNumberLast4}", x.ProductName ?? "-", Spaced(x.Status), N(x.Balance) ?? "-",
                        x.Activity is { } act ? $"{N(act.CreditsInWindow)} ({act.WindowMonths}m)" : "Not read", D(x.LastTransaction) ?? "-",
                    }), [1.1f, 2, 1, 1.3f, 1.6f, 1.2f]);
        });
    }

    private static void Loans(ColumnDescriptor col, BankLoansSection l)
    {
        Section(col, "Loans with the bank", l.Status, l.Reason, c =>
        {
            if (l.Loans.Count == 0)
            {
                c.Item().Text("No loans booked in core banking.").FontSize(8);
                return;
            }
            Grid(c, ["Loan", "Product", "Principal", "Outstanding", "Overdue", "Days past due", "Status"],
                l.Loans.Select(x => new[]
                {
                    $"****{x.LoanAccountLast4}", x.ProductName ?? "-", N(x.Principal)!, N(x.Outstanding) ?? "-",
                    N(x.OverdueAmount) ?? "-", x.DaysPastDue?.ToString() ?? "-", Spaced(x.Status),
                }), [1, 2, 1.2f, 1.2f, 1.1f, 0.9f, 1]);
        });
    }

    private static void Crms(ColumnDescriptor col, CrmsFacilitiesSection f)
    {
        Section(col, "Cases in the CRMS", f.Status, f.Reason, c =>
        {
            if (f.Relationships.Count == 0)
            {
                c.Item().Text("No CRMS case found.").FontSize(8);
                return;
            }
            Grid(c, ["Case", "Track", "Role", "Borrower", "Status", "Amount"],
                f.Relationships.Select(x => new[]
                {
                    x.CaseReference, x.Track, Spaced(x.Role), x.Obligor, Spaced(x.Status), N(x.AmountApproved) ?? "-",
                }), [1.5f, 0.9f, 1.3f, 2.2f, 1, 1.2f]);
        });
    }

    private static void Advisory(ColumnDescriptor col, AiAdvisorySection a)
    {
        Section(col, "AI advisory", a.Status, a.Reason, c =>
        {
            Grid(c, ["Category", "Score", "Weight", "Rating", "Rationale"],
                a.Categories.Select(x => new[]
                {
                    Spaced(x.Category), x.Assessed ? $"{x.Score:N1}" : "Not assessed", $"{x.Weight:P0}", Spaced(x.Rating) ?? "-",
                    x.Assessed ? x.Rationale : x.Rationale[(x.Rationale.IndexOf('|') + 1)..],
                }), [1.4f, 0.8f, 0.6f, 0.8f, 4]);
            if (a.RedFlags.Count > 0)
                Bullets(c, "Red flags", a.RedFlags, Red);
            if (a.Conditions.Count > 0)
                Bullets(c, "Conditions", a.Conditions, Primary);
            if (a.Narrative is { } n)
            {
                c.Item().PaddingTop(6).Text("Summary").SemiBold().FontSize(8.5f);
                c.Item().Text(n.Summary).FontSize(8);
                if (!string.IsNullOrWhiteSpace(n.Strengths)) { c.Item().PaddingTop(3).Text("Strengths").SemiBold().FontSize(8); c.Item().Text(n.Strengths).FontSize(8); }
                if (!string.IsNullOrWhiteSpace(n.Weaknesses)) { c.Item().PaddingTop(3).Text("Weaknesses").SemiBold().FontSize(8); c.Item().Text(n.Weaknesses).FontSize(8); }
            }
            if (a.Proposal is { } p)
                c.Item().PaddingTop(4).Text($"Measured against NGN {p.Amount:N0} over {p.TenorMonths} months{(p.Supplied ? "" : " (assumed; none was given)")}."
                    + (p.RecommendedAmount is { } ra ? $" The rules would lend NGN {ra:N0} over {p.RecommendedTenorMonths} months." : "")).FontSize(7.5f).Italic();
            if (a.Basis is not null)
                c.Item().PaddingTop(2).Text(a.Basis).FontSize(7.5f).FontColor(Colors.Grey.Darken1);
        });
    }

    // ── Building blocks ──────────────────────────────────────────────────────────────────────────

    private static void Section(ColumnDescriptor col, string title, string status, string? reason, Action<ColumnDescriptor> body)
    {
        col.Item().PaddingBottom(9).Column(s =>
        {
            s.Item().Background(Color.FromHex(Primary)).PaddingVertical(3).PaddingHorizontal(6).Row(r =>
            {
                r.RelativeItem().Text(title.ToUpperInvariant()).Bold().FontSize(8.5f).FontColor(Colors.White);
                r.ConstantItem(120).AlignRight().Text(StatusWord(status)).FontSize(7.5f).FontColor(Color.FromHex(Subtle));
            });
            s.Item().Border(0.5f).BorderColor(Color.FromHex(MedGray)).Padding(6).Column(c =>
            {
                if (status is SectionStatuses.Ok)
                {
                    body(c);
                    if (!string.IsNullOrWhiteSpace(reason))
                        c.Item().PaddingTop(4).Text(reason).FontSize(7.5f).Italic().FontColor(Colors.Grey.Darken1);
                }
                else
                    c.Item().Text(reason ?? StatusWord(status)).FontSize(8).Italic().FontColor(Colors.Grey.Darken2);
            });
        });
    }

    private static void Facts(ColumnDescriptor c, params (string Label, string? Value)[] facts)
    {
        var shown = facts.Where(f => !string.IsNullOrWhiteSpace(f.Value)).ToList();
        if (shown.Count == 0) return;
        c.Item().Table(t =>
        {
            t.ColumnsDefinition(d => { d.RelativeColumn(1); d.RelativeColumn(2); d.RelativeColumn(1); d.RelativeColumn(2); });
            foreach (var (label, value) in shown)
            {
                t.Cell().PaddingVertical(1.5f).Text(label).FontSize(7.5f).FontColor(Colors.Grey.Darken2);
                t.Cell().PaddingVertical(1.5f).Text(value!).FontSize(8);
            }
        });
    }

    private static void Grid(ColumnDescriptor c, string[] headers, IEnumerable<string[]> rows, float[] widths)
    {
        c.Item().PaddingTop(4).Table(t =>
        {
            t.ColumnsDefinition(d => { foreach (var w in widths) d.RelativeColumn(w); });
            t.Header(h =>
            {
                foreach (var head in headers)
                    h.Cell().Background(Color.FromHex(LightGray)).BorderBottom(0.5f).BorderColor(Color.FromHex(MedGray))
                        .Padding(3).Text(head).SemiBold().FontSize(7.5f);
            });
            foreach (var row in rows)
                foreach (var cell in row)
                    t.Cell().BorderBottom(0.25f).BorderColor(Color.FromHex(MedGray)).Padding(3).Text(cell).FontSize(7.5f);
        });
    }

    private static void Bullets(ColumnDescriptor c, string title, IEnumerable<string> items, string colour)
    {
        c.Item().PaddingTop(5).Text(title).SemiBold().FontSize(8.5f).FontColor(Color.FromHex(colour));
        foreach (var i in items)
            c.Item().Text($"• {i}").FontSize(8);
    }

    private static string StatusWord(string status) => status switch
    {
        SectionStatuses.Ok => "Answered",
        SectionStatuses.NoRecord => "No record",
        SectionStatuses.Unavailable => "Unavailable",
        SectionStatuses.NotRequested => "Not run",
        SectionStatuses.NotAllowed => "Not allowed",
        SectionStatuses.NotPossible => "Not possible",
        _ => status,
    };

    private static string ScoreColour(decimal? score) => score switch
    {
        >= 70 => Accent,
        >= 50 => Amber,
        null => "#4a5568",
        _ => Red,
    };

    private static DateTime Local(DateTime utc) => utc + Wat;
    private static string? D(DateOnly? d) => d?.ToString("dd MMM yyyy");
    private static string? N(decimal? v) => v is null ? null : $"{v:N2}";

    /// <summary>"ApproveWithConditions" → "Approve With Conditions"; "WRITTEN_OFF" → "Written off".</summary>
    private static string Spaced(string? value)
    {
        if (string.IsNullOrWhiteSpace(value)) return "-";
        if (value.Contains('_') || value.All(ch => !char.IsLetter(ch) || char.IsUpper(ch)))
        {
            var words = value.Replace('_', ' ').ToLowerInvariant();
            return char.ToUpperInvariant(words[0]) + words[1..];
        }
        var sb = new System.Text.StringBuilder();
        foreach (var ch in value)
        {
            if (char.IsUpper(ch) && sb.Length > 0) sb.Append(' ');
            sb.Append(ch);
        }
        return sb.ToString();
    }
}
